import { createImage, resize } from "../src/pixels";
import type { RawImage, ResizeKernel } from "../src/types";

const SRC_WIDTH = 4000;
const SRC_HEIGHT = 3000;

function makeSynthetic(width: number, height: number): RawImage {
  const image = createImage(width, height);
  const { data } = image;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 4;
      data[i] = (x * 255) / width;
      data[i + 1] = (y * 255) / height;
      data[i + 2] = ((x ^ y) & 0xff) / 2;
      data[i + 3] = 255;
    }
  }
  return image;
}

interface Result {
  kernel: ResizeKernel;
  target: string;
  ms: number;
  mpixPerSecond: number;
}

function time<T>(fn: () => T): number {
  const started = process.hrtime.bigint();
  const value = fn();
  void value;
  const ended = process.hrtime.bigint();
  return Number(ended - started) / 1e6;
}

const source = makeSynthetic(SRC_WIDTH, SRC_HEIGHT);
console.log(
  `source: ${SRC_WIDTH}x${SRC_HEIGHT} (${((SRC_WIDTH * SRC_HEIGHT) / 1e6).toFixed(1)} MPix), ` +
    `node ${process.version}, ${process.arch}`,
);
console.log(`cpus: ${(await import("node:os")).cpus().length}\n`);

const targets = [
  { label: "1000x750", width: 1000, height: 750 },
  { label: "400x300", width: 400, height: 300 },
  { label: "200x200", width: 200, height: 200 },
];

const kernels: ResizeKernel[] = [
  "nearest",
  "bilinear",
  "catmull-rom",
  "lanczos3",
];
const results: Result[] = [];

for (const target of targets) {
  for (const kernel of kernels) {
    resize(source, {
      width: target.width,
      height: target.height,
      fit: "fill",
      kernel,
    });
    const runs = [0, 1].map(() =>
      time(() =>
        resize(source, {
          width: target.width,
          height: target.height,
          fit: "fill",
          kernel,
        }),
      ),
    );
    const ms = Math.min(...runs);
    results.push({
      kernel,
      target: target.label,
      ms,
      mpixPerSecond: (SRC_WIDTH * SRC_HEIGHT) / 1e6 / (ms / 1000),
    });
  }
}

const small = makeSynthetic(1000, 750);
const upscaleMs = <T>(fn: () => T): number => time(fn);

const lines: string[] = [];
lines.push("| kernel | target | ms | MPix/s |");
lines.push("| --- | --- | ---: | ---: |");
for (const result of results) {
  lines.push(
    `| ${result.kernel} | ${result.target} | ${result.ms.toFixed(0)} | ${result.mpixPerSecond.toFixed(1)} |`,
  );
}

const upscale = upscaleMs(() =>
  resize(small, { width: 2000, height: 1500, fit: "fill", kernel: "lanczos3" }),
);
lines.push("");
lines.push(
  `Upscale 1000x750 -> 2000x1500 (lanczos3): ${upscale.toFixed(0)} ms`,
);
lines.push(
  `Downscale 4000x3000 -> 1000x750 nearest: ${results[0].ms.toFixed(0)} ms`,
);

const table = lines.join("\n");
console.log(table);

const { writeFileSync, mkdirSync } = await import("node:fs");
mkdirSync(".bench", { recursive: true });
writeFileSync(
  ".bench/resize.md",
  [
    `# resize benchmarks`,
    "",
    `Generated by \`pnpm bench\` on ${new Date().toISOString()}.`,
    "",
    `Source: ${SRC_WIDTH}x${SRC_HEIGHT} synthetic RGBA, node ${process.version} (${process.arch}).`,
    "",
    table,
    "",
  ].join("\n"),
);
console.log("\nwritten to .bench/resize.md");
